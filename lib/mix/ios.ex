defmodule Mix.Ios do
  @moduledoc """
  What `mix ios.test` and `mix ios.deploy` share: finding Apple's command-line
  tools, generating the Xcode project, and running `xcodebuild` while its output
  is read line by line.

  The functions take the options the tasks' tests use to stay away from Xcode:

    * `:root` - the repository root, default the current directory
    * `:find_executable` - finds a tool by name, default `find_executable/1`
  """

  @project "mobile/ios/Stride.xcodeproj"
  @project_spec "mobile/ios/project.yml"
  @scheme "Stride"
  @default_simulator "iPhone 17"

  # Homebrew's folders, which a Stride hook may start without.
  @extra_dirs ["/opt/homebrew/bin", "/usr/local/bin"]

  # A port's program outlives the VM: when mix is killed, as a hook's deadline
  # does, or stopped with Ctrl-C, xcodebuild would run on. The VM's end closes
  # this shell's stdin, which stops the program.
  @watched """
  exec 3<&0
  "$@" < /dev/null 3<&- &
  program=$!
  { while read -r _; do :; done; kill "$program"; } <&3 > /dev/null 2>&1 &
  watcher=$!
  wait "$program"
  status=$?
  kill "$watcher" 2> /dev/null
  exit "$status"
  """

  @doc "The simulator the tasks use: `IOS_SIMULATOR`, or an iPhone 17."
  @spec default_simulator() :: String.t()
  def default_simulator do
    case System.get_env("IOS_SIMULATOR", "") do
      "" -> @default_simulator
      simulator -> simulator
    end
  end

  @doc """
  Splits a task's arguments at `--` into the task's own and the ones for
  `xcodebuild`.
  """
  @spec split_args([String.t()]) :: {[String.t()], [String.t()]}
  def split_args(args) do
    {own, rest} = Enum.split_while(args, &(&1 != "--"))
    {own, Enum.drop(rest, 1)}
  end

  @doc "Finds a tool on the `PATH` or in Homebrew's folders."
  @spec find_executable(String.t()) :: String.t() | nil
  def find_executable(name) do
    System.find_executable(name) ||
      Enum.find_value(@extra_dirs, &System.find_executable(Path.join(&1, name)))
  end

  @doc "Generates the git-ignored Xcode project from `mobile/ios/project.yml`."
  @spec generate_project!(keyword()) :: :ok
  def generate_project!(opts) do
    {output, status} = capture("xcodegen", ["generate", "--quiet", "--spec", @project_spec], opts)

    if status != 0 do
      Mix.raise("xcodegen could not generate the iOS project:\n" <> String.trim(output))
    end

    :ok
  end

  @doc """
  The arguments of an `xcodebuild` call on the `Stride` scheme. `action` is what
  comes first, such as `["test"]`.

  StrideKit's client is generated by a package plugin, which `xcodebuild` asks a
  person to trust unless told not to. `Package.swift` pins its exact version.
  """
  @spec xcodebuild_args([String.t()], String.t(), [String.t()]) :: [String.t()]
  def xcodebuild_args(action, destination, extra) do
    action ++
      ["-project", @project, "-scheme", @scheme, "-skipPackagePluginValidation"] ++
      ["-destination", destination] ++ extra
  end

  @doc """
  Runs a tool to its end and returns its output, errors included, and its exit
  status. With `stderr: :discard` the output holds no errors.
  """
  # The tools are the fixed names this namespace calls.
  # sobelow_skip ["CI.System"]
  @spec capture(String.t(), [String.t()], keyword()) :: {String.t(), non_neg_integer()}
  def capture(name, args, opts) do
    tool = find!(name, opts)

    {executable, args} =
      case opts[:stderr] do
        :discard -> {"/bin/sh", ["-c", ~S("$@" 2> /dev/null), "sh", tool | args]}
        nil -> {tool, args}
      end

    System.cmd(executable, args, cd: root(opts), stderr_to_stdout: true)
  end

  @doc """
  Runs a tool and folds its output into `acc`, one line at a time as it is
  printed. Returns `acc` and the exit status. The tool is stopped if this VM
  ends first.
  """
  @spec stream(String.t(), [String.t()], acc, (String.t(), acc -> acc), keyword()) ::
          {acc, non_neg_integer()}
        when acc: term()
  def stream(name, args, acc, fun, opts) do
    port =
      Port.open({:spawn_executable, "/bin/sh"}, [
        :binary,
        :exit_status,
        :stderr_to_stdout,
        cd: root(opts),
        args: ["-c", @watched, "sh", find!(name, opts) | args]
      ])

    collect(port, "", acc, fun)
  end

  @doc "The repository root the tools run in."
  @spec root(keyword()) :: String.t()
  def root(opts), do: Keyword.get_lazy(opts, :root, &File.cwd!/0)

  # The exit status comes after all the output.
  defp collect(port, partial, acc, fun) do
    receive do
      {^port, {:data, data}} ->
        {lines, [partial]} = split_lines(partial <> data)
        collect(port, partial, Enum.reduce(lines, acc, fun), fun)

      {^port, {:exit_status, status}} ->
        {partial |> last_line() |> Enum.reduce(acc, fun), status}
    end
  end

  # A character can come in two pieces, so only whole lines are checked.
  defp split_lines(text) do
    {lines, partial} = text |> String.split("\n") |> Enum.split(-1)
    {Enum.map(lines, &String.replace_invalid/1), partial}
  end

  defp last_line(""), do: []
  defp last_line(text), do: [String.replace_invalid(text)]

  defp find!(name, opts) do
    find = Keyword.get(opts, :find_executable, &find_executable/1)
    find.(name) || Mix.raise("#{name} is not installed. #{install_hint(name)}")
  end

  defp install_hint("xcodegen"), do: "Install XcodeGen (brew install xcodegen) and try again."
  defp install_hint(_), do: "Install Xcode, on a Mac, and try again."
end
