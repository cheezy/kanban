    """
  end

  # Every caller passes a local-day `Date` bucket, which LocalTime never shifts,
  # so the zone argument is immaterial; the locale still applies.
  defp format_date(nil), do: gettext("N/A")
  defp format_date(date), do: LocalTime.format(date, :short_date, "Etc/UTC")

  # A timestamp is shifted into the requester's zone and written in the
  # request's locale.
  defp format_datetime(nil, _zone), do: gettext("N/A")
  defp format_datetime(datetime, zone), do: LocalTime.format(datetime, :datetime, zone)

  defp times_shown_in(zone), do: Helpers.times_shown_in(zone)

  defp format_time(seconds) do
    KanbanWeb.MetricsLive.Helpers.format_time(seconds)
  end

  # The five shared range labels come from KanbanWeb.MetricsLive.Helpers so this
  # module and KanbanWeb.MetricsExcelExport cannot drift; only the fallback,
  # which the two have always disagreed on, stays local.
  defp format_time_range(range) do
    KanbanWeb.MetricsLive.Helpers.time_range_label(range) || gettext("Custom Range")
  end

  # An agent name is user data and is rendered, not translated.
  defp agent_filter_label(nil), do: gettext("All Agents")
  defp agent_filter_label(name), do: name

  defp weekend_filter_label(true), do: gettext("Weekends Excluded")
  defp weekend_filter_label(false), do: gettext("Weekends Included")

  defp calculate_bar_width(_count, nil), do: 0
  defp calculate_bar_width(_count, peak) when peak == 0, do: 0

  defp calculate_bar_width(count, peak) when peak > 0 do
    Float.round(count / peak * 100, 1)
  end

  defp format_short_date(date), do: LocalTime.format(date, :month_day, "Etc/UTC")

  defp line_chart_points(daily_times, chart_width, chart_height, max_val) when max_val > 0 do
    count = length(daily_times)

    daily_times
    |> Enum.with_index()
    |> Enum.map(&line_chart_point(&1, count, chart_width, chart_height, max_val))
  end

  defp line_chart_points(_daily_times, chart_width, chart_height, _max_val) do
    [{Float.round(chart_width / 2.0, 1), Float.round(chart_height / 2.0, 1)}]
  end

  defp line_chart_point({day, i}, count, chart_width, chart_height, max_val) do
    padding = 0

    x =
      if count > 1,
        do: padding + i / (count - 1) * (chart_width - 2 * padding),
        else: chart_width / 2

    y = chart_height - day.average_hours / max_val * chart_height
    {Float.round(x * 1.0, 1), Float.round(y * 1.0, 1)}
  end

  defp points_to_polyline(points) do
    Enum.map_join(points, " ", fn {x, y} -> "#{x},#{y}" end)
  end

  defp line_chart_y_labels(max_val, count) when max_val > 0 do
    Enum.map(0..(count - 1), fn i ->
      Float.round(max_val * i / (count - 1), 1)
    end)
  end

  defp line_chart_y_labels(_max_val, _count), do: [0.0]
end
