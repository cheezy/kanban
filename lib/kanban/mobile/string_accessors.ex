defmodule Kanban.Mobile.StringAccessors do
  @moduledoc """
  Builds `mobile/ios/Stride/DesignSystem/L10n.swift` (W2788), the iOS app's
  typed accessors for the strings that take arguments. `mix mobile.strings`
  writes it beside the string catalog.

  Xcode makes a Swift symbol of every catalog entry, but names no positional
  argument: `target_risk_slip` becomes `.targetRiskSlip(_:_:)`, two strings a
  caller could swap. Each accessor here names its arguments after the
  placeholders, in camel case, so it is `.targetRiskSlip(estimate:targetDate:)`.
  `{count}` and `{done}` are `Int`, every other placeholder is `String`. A
  string without arguments needs no accessor: use Xcode's symbol, such as
  `.targetStatusOnTrack`.

  `test/kanban/mobile/string_accessors_test.exs` fails while the committed file
  is stale. Refresh it with `MIX_ENV=test mix mobile.strings`.
  """
  alias Kanban.Mobile.StringCatalog
  alias Kanban.Mobile.Strings

  @output_path "mobile/ios/Stride/DesignSystem/L10n.swift"
  @source_locale "en"

  @doc "The accessors file, relative to the project root."
  @spec output_path() :: String.t()
  def output_path, do: @output_path

  @doc """
  Renders the accessors from what `Kanban.Mobile.Strings.build!/1` returns,
  sorted by key and ending in a newline.
  """
  @spec render(%{String.t() => Strings.locale_strings()}) :: String.t()
  def render(strings_by_locale) do
    accessors =
      strings_by_locale[@source_locale]
      |> texts_with_arguments()
      |> Enum.map_join("\n", &accessor/1)

    """
    // Generated by `mix mobile.strings` from the mobile gettext domain.
    // Never edit this file by hand: change lib/kanban/mobile/strings.ex and the
    // mobile.po files, then run the task.

    import Foundation

    /// The strings that take arguments, each argument named after its
    /// placeholder. Xcode's own symbols for them name no argument, so call these.
    extension LocalizedStringResource {
    #{accessors}}
    """
  end

  # Each string and each plural's `other` form that has a placeholder, with the
  # placeholder names, sorted by key.
  defp texts_with_arguments(source) do
    texts =
      for {key, text} <- Enum.to_list(source["strings"]) ++ plural_texts(source),
          arguments = StringCatalog.arguments(text),
          arguments != [] do
        {key, text, arguments}
      end

    Enum.sort(texts)
  end

  defp plural_texts(source) do
    for {key, %{"other" => text}} <- Map.get(source, "plurals", %{}), do: {key, text}
  end

  defp accessor({key, text, arguments}) do
    parameters = Enum.map_join(arguments, ", ", &"#{camel(&1)}: #{swift_type(&1)}")

    """
        /// #{doc(text)}
        static func #{camel(key)}(#{parameters}) -> LocalizedStringResource {
            LocalizedStringResource("#{key}", defaultValue: "#{default_value(text)}", table: "Localizable", bundle: .main)
        }
    """
  end

  # The English text as a Swift string literal, each placeholder interpolated,
  # so a key missing from the table still reads as a sentence.
  defp default_value(text) do
    text
    |> String.replace("\\", "\\\\")
    |> String.replace("\"", "\\\"")
    |> String.replace("\n", "\\n")
    |> then(&Regex.replace(~r/\{(\w+)\}/, &1, fn _match, name -> interpolate(name) end))
  end

  defp interpolate(name) do
    if StringCatalog.integer?(name),
      do: ~s|\\(#{camel(name)}, specifier: "%lld")|,
      else: "\\(#{camel(name)})"
  end

  defp swift_type(name), do: if(StringCatalog.integer?(name), do: "Int", else: "String")

  defp doc(text), do: "\"" <> String.replace(text, ~r/\s+/, " ") <> "\""

  defp camel(name) do
    [first | rest] = String.split(name, "_")
    Enum.join([first | Enum.map(rest, &String.capitalize/1)])
  end
end
