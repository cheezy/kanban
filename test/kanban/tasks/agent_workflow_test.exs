defmodule Kanban.Tasks.AgentWorkflowTest do
  @moduledoc """
  Drift guard for the public API of the `Kanban.Tasks.AgentWorkflow` facade
  (W2356).

  The behaviour tests live in `test/kanban/tasks/agent_workflow/`, split by
  concern and still calling the facade. This file pins what the facade exports,
  so the W2355 extractions behind it cannot drop a function, change an arity
  or lose a default argument without a red test.
  """
  use Kanban.DataCase, async: true

  alias Kanban.Tasks.AgentWorkflow

  # The exact name/arity set exported before the split, including the arities
  # generated by default arguments, in sorted order.
  @exports [
    {:authorized_reviewer?, 2},
    {:claim_next_task, 2},
    {:claim_next_task, 3},
    {:claim_next_task, 4},
    {:claim_next_task, 5},
    {:complete_task, 3},
    {:complete_task, 4},
    {:mark_done, 2},
    {:mark_reviewed, 2},
    {:mark_reviewed, 3},
    {:unclaim_task, 2},
    {:unclaim_task, 3}
  ]

  describe "public API" do
    test "exports exactly the documented public functions and arities" do
      assert AgentWorkflow.__info__(:functions) |> Enum.sort() == @exports
    end

    test "documents every public function" do
      assert {:docs_v1, _anno, :elixir, _format, _moduledoc, _meta, docs} =
               Code.fetch_docs(AgentWorkflow)

      # A function with default arguments has one docs entry, at its highest
      # arity, so the check is by name. `@doc false` is `:hidden`, not a map,
      # so a hidden function never counts as documented.
      documented =
        for {{:function, name, _arity}, _line, _signature, %{"en" => text}, _meta} <- docs,
            String.trim(text) != "",
            uniq: true,
            do: name

      names = @exports |> Enum.map(&elem(&1, 0)) |> Enum.uniq()

      assert names -- documented == []
    end
  end
end
